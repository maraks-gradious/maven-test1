public class Utility {
    
    // Utility function to check if a number is odd or even
    public void AnjiOddEven(int number) {
        System.out.println("I am Anji");
        if (number % 2 == 0) {
            System.out.println(number + " is Even");
        } else {
            System.out.println(number + " is Odd");
        }
    }
}