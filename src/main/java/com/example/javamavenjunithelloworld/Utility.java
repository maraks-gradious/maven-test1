package com.example.javamavenjunithelloworld;

public class Utility {
    public static void printTenNumbers(){
        for(int i=1;i<=10;i++){
            System.out.print(i+" ");
        }
        System.out.println();
    }
    public static void pravallika() {
        System.out.println("I am Pravallika");
    }

    public static void main(String[] args) {
        printTenNumbers();
        pravallika();
    }
}
